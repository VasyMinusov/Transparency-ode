"""Версия набора данных и инвалидация кэшей.

Кэши (граф, центральности, вердикты, сигналы) живут до смены данных:
перезагрузка адаптеров (POST /load) или повторный seed увеличивают версию.
Решения сотрудника на данные не влияют — кэши не трогаем.
"""
DATA_VERSION = {"v": 0}


def bump() -> int:
    DATA_VERSION["v"] += 1
    return DATA_VERSION["v"]


def version() -> int:
    return DATA_VERSION["v"]
